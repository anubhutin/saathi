#!/usr/bin/env python3
"""Build the SAATHI static site.

Usage:  python3 tools/build.py
Writes HTML files to the repository root (served by GitHub Pages as-is),
and generates assets/js/i18n-strings.js from locales/*.json.

Every module in tools/pages/ that defines PAGES is rendered. A module may
also define build_assets(repo_root) to write generated JS/JSON.
"""
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools/pages"))

from layout import render_page  # noqa: E402


def build_i18n():
    strings = {}
    for f in sorted((ROOT / "locales").glob("*.json")):
        strings[f.stem] = json.loads(f.read_text(encoding="utf-8"))
    out = ROOT / "assets/js/i18n-strings.js"
    out.write_text(
        "/* Generated by tools/build.py from locales/*.json. Do not edit. */\n"
        "window.SAATHI_STRINGS = " + json.dumps(strings, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )


def main():
    build_i18n()
    count = 0
    for mod_path in sorted((ROOT / "tools/pages").glob("*.py")):
        if mod_path.name.startswith("_"):
            continue
        spec = importlib.util.spec_from_file_location(mod_path.stem, mod_path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        if hasattr(mod, "build_assets"):
            mod.build_assets(ROOT)
        for page in getattr(mod, "PAGES", []):
            out = ROOT / page["path"]
            out.parent.mkdir(parents=True, exist_ok=True)
            depth = len(pathlib.PurePosixPath(page["path"]).parts) - 1
            out.write_text(render_page(page, depth), encoding="utf-8")
            count += 1
    print(f"Built {count} pages.")


if __name__ == "__main__":
    main()
